// ── 5. Resolver Helpers ───────────────────────────────────────────────────────

/**
 * Resolves a genuine photograph for any given fabric name.
 * Returns URL string if matched, or null for graceful fallback.
 */
export function getFabricRealPhoto(fabricName = '') {
  if (!fabricName) return null;
  const clean = fabricName.trim().toLowerCase();

  // Direct lookup
  if (FABRIC_REAL_PHOTOS[clean]) {
    return FABRIC_REAL_PHOTOS[clean];
  }

  // Substring match: check longer/more specific keys first (e.g. 'linen blend' before 'linen')
  const sortedKeys = Object.keys(FABRIC_REAL_PHOTOS).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    if (clean.includes(key) || key.includes(clean)) {
      return FABRIC_REAL_PHOTOS[key];
    }
  }

  // Default to cotton weave photography rather than CSS gradients
  return FABRIC_REAL_PHOTOS['cotton'];
}

/**
 * Resolves a genuine photograph for design/collar/cuff/sleeve/button options.
 */
export function getStyleRealPhoto(sectionType = '', optionId = '') {
  const typeClean = (sectionType || '').toLowerCase();
  const idClean = (optionId || '').toLowerCase();

  // 1. Check neckline / collar dictionary
  if (typeClean === 'collar' || typeClean.includes('neck') || typeClean.includes('hood') || typeClean.includes('lapel')) {
    if (NECKLINE_REAL_PHOTOS[idClean]) return NECKLINE_REAL_PHOTOS[idClean];
    for (const [key, url] of Object.entries(NECKLINE_REAL_PHOTOS)) {
      if (idClean.includes(key) || key.includes(idClean)) return url;
    }
  }

  // 2. Check details dictionary (cuffs, sleeves, pockets, buttons)
  if (DETAIL_REAL_PHOTOS[idClean]) return DETAIL_REAL_PHOTOS[idClean];
  for (const [key, url] of Object.entries(DETAIL_REAL_PHOTOS)) {
    if (idClean.includes(key) || key.includes(idClean)) return url;
  }

  // 3. Fallback check across both dictionaries
  for (const [key, url] of Object.entries(NECKLINE_REAL_PHOTOS)) {
    if (idClean.includes(key)) return url;
  }
  for (const [key, url] of Object.entries(DETAIL_REAL_PHOTOS)) {
    if (idClean.includes(key)) return url;
  }

  return null;
}

/**
 * Resolves a genuine real-model fit photograph.
 */
export function getFitRealPhoto(fitId = 'Regular') {
  if (!fitId) return FIT_REAL_PHOTOS['Regular'].url;
  const clean = fitId.trim();
  if (FIT_REAL_PHOTOS[clean]) return FIT_REAL_PHOTOS[clean].url;
  const lower = clean.toLowerCase();
  if (lower.includes('slim')) return FIT_REAL_PHOTOS['Slim'].url;
  if (lower.includes('relaxed')) return FIT_REAL_PHOTOS['Relaxed'].url;
  return FIT_REAL_PHOTOS['Regular'].url;
}
